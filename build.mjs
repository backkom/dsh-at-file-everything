/**
 * Build script: bundles the plugin entry and the pure helper entry.
 *
 * `lib/index.js` is the plugin the Harness loads; it keeps `@deepseek-ai/*`
 * imports external because the host resolves those packages from the
 * installation at runtime. Inlining them would give this plugin a second Cordis
 * `Service` class identity, which breaks `instanceof` across the seam.
 *
 * `lib/pure.js` holds the ranking and search-syntax helpers with no Harness
 * imports at all, so they can be unit-tested (and reused) on a machine with no
 * Harness installation.
 */

import { build } from 'esbuild'
import { rm } from 'node:fs/promises'

await rm('lib', { recursive: true, force: true })

const shared = {
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: '// dsh-at-file-everything — generated by build.mjs; edit src/ instead.',
  },
}

await build({
  ...shared,
  entryPoints: ['src/index.ts'],
  outfile: 'lib/index.js',
  // Provided by the Harness installation at runtime.
  external: ['@deepseek-ai/*'],
})

await build({
  ...shared,
  entryPoints: ['src/pure.ts'],
  outfile: 'lib/pure.js',
})

console.log('built lib/index.js and lib/pure.js')

