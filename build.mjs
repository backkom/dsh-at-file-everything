/**
 * Build script: bundles the host entries and the browser half.
 *
 * `lib/index.js` is the plugin the Harness loads; it keeps `@deepseek-ai/*`
 * imports external because the host resolves those packages from the
 * installation at runtime. Inlining them would give this plugin a second Cordis
 * `Service` class identity, which breaks `instanceof` across the seam.
 *
 * `lib/pure.js` holds the ranking and search-syntax helpers with no Harness
 * imports at all, so they can be unit-tested (and reused) on a machine with no
 * Harness installation.
 *
 * `lib/client.js` is the browser half. The Web shell does not import it as an ES
 * module: it evaluates the file as a script and expects it to register a lazy
 * CommonJS factory with `window.__ModuleLoader__.load({ id, factory })`. So it is
 * built as CommonJS (the factory is `require`-based), with `react` left external
 * because the shell's module table provides it — bundling React would give the
 * page a second React and break every hook in the card.
 */

import { build } from 'esbuild'
import { rm } from 'node:fs/promises'

await rm('lib', { recursive: true, force: true })

const shared = {
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: '// dsh-at-file-everything — generated by build.mjs; edit src/ instead.',
  },
}

await build({
  ...shared,
  entryPoints: ['src/index.ts'],
  outfile: 'lib/index.js',
  // Provided by the Harness installation at runtime.
  external: ['@deepseek-ai/*'],
})

await build({
  ...shared,
  entryPoints: ['src/pure.ts'],
  outfile: 'lib/pure.js',
})

// Configuration validation, as its own entry: none of it imports the Harness, and
// it must be testable in plain Node — including the volatile-handle case that once
// left the whole bundle inactive.
await build({
  ...shared,
  entryPoints: ['src/config.ts'],
  outfile: 'lib/config.js',
})

// The tool definition, as a separate entry so the suite can drive it with a
// stubbed `dsh-tools` instead of a Harness installation.
await build({
  ...shared,
  entryPoints: ['src/tool.ts'],
  outfile: 'lib/tool.js',
  external: ['@deepseek-ai/*'],
})

// The browser half, as a lazy-CJS registration rather than an ES module.
await build({
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  sourcemap: false,
  legalComments: 'none',
  entryPoints: ['src/client.ts'],
  outfile: 'lib/client.cjs.js',
  // The shell's module table supplies these; a bundled React would be a second
  // copy, and `react/jsx-runtime` is only needed if JSX is used (it is not).
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  banner: {
    js: [
      '// dsh-at-file-everything — generated by build.mjs; edit src/ instead.',
      'window.__ModuleLoader__.load({',
      "  id: 'dsh-at-file-everything',",
      '  factory: function (require) {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
    ].join('\n'),
  },
  footer: {
    js: ['    return module.exports;', '  },', '});'].join('\n'),
  },
})

console.log('built lib/index.js, lib/pure.js, lib/config.js, lib/tool.js and lib/client.cjs.js')
